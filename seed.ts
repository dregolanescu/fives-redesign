const heroConfig = {
  displayMode: "single",
  transitionDuration: 8,
  transitionType: "crossfade",
  autoplay: true,
  showNavigation: true,
}

async function seed() {
  console.log('🌱 Starting seed...')
  const payload = await getPayload({ config: configPromise })

  // Seed articles
  for (const article of articles) {
    const existing = await payload.find({ collection: 'articles', where: { slug: { equals: article.slug } }, limit: 1 })
    if (existing.docs.length > 0) {
      console.log(`  ⏭ Article "${article.slug}" already exists, skipping`)
      continue
    }
    await payload.create({ collection: 'articles', data: article as any })
    console.log(`  ✅ Created article: ${article.title}`)
  }

  // Seed hero slide (without video — will link manually later)
  const existingSlides = await payload.find({ collection: 'hero-slides', limit: 1 })
  if (existingSlides.docs.length === 0) {
    await payload.create({ collection: 'hero-slides', data: heroSlide as any })
    console.log('  ✅ Created hero slide')
  } else {
    console.log('  ⏭ Hero slide already exists, skipping')
  }

  // Seed hero config global
  await payload.updateGlobal({ slug: 'hero-config', data: heroConfig as any })
  console.log('  ✅ Updated hero config global')

  console.log('🎉 Seed complete!')
  process.exit(0)
}

seed().catch((err) => {
  console.error('Seed failed:', err)
  process.exit(1)
})
